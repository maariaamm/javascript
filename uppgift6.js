"use strict";

// Beräknar arean av en rektangel och returnerar resultatet
function calculateArea(width, height) {
  return width * height;
}
// Anropar funktionen tre gånger med olika värden och skriver ut resultaten
console.log("Arean är " + calculateArea(6, 5));
console.log("Arean är " + calculateArea(6, 2));
console.log("Arean är " + calculateArea(8, 10));
